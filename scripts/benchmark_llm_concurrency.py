"""Replay identical game requests against the configured API at 1/2/4 concurrency.

No API request is made without --live. This is a transport/validation benchmark,
not a concurrent game implementation: later fixtures contain scripted earlier
speeches, never outputs generated by another measured job. Production files and
the current game are untouched. Only accepted public prose and allowlisted
metrics are saved, never credentials, raw responses, beliefs or reasoning.
"""

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
from contextlib import contextmanager
from copy import deepcopy
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import statistics
import sys
import threading
import time
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from avalon import llm
from avalon.agents import Agent
from avalon.engine import Game, Player
from avalon.evil_strategy import EvilStrategyManager


def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                     allow_nan=False).encode()).hexdigest()


class Captured(Exception):
    pass


class CaptureClient:
    def complete(self, context):
        self.context = deepcopy(context)
        raise Captured


def fixtures():
    """Four legal, independent snapshots, covering both production protocols."""
    names = ["YOU", "NOVA", "ATLAS", "ECHO", "SAGE"]
    roles = ["GOOD", "MERLIN", "ASSASSIN", "EVIL", "GOOD"]
    game = Game([Player(f"P{i + 1}", names[i], role) for i, role in enumerate(roles)],
                seed=7, direction="clockwise")
    assert game.leader == "P1"
    manager = EvilStrategyManager(game.ids, {"P3", "P4"}, seed=7)
    agents = {pid: Agent(game.view(pid), CaptureClient()) for pid in game.ids[1:]}
    for pid in manager.controlled_evil_ids:
        agents[pid].bind_evil_strategy(manager)
    cursor = 0

    def observe():
        nonlocal cursor
        for event in game.events[cursor:]:
            manager.observe(event)
            for agent in agents.values():
                agent.observe(event)
        cursor = len(game.events)

    game.propose("P1", ["P1", "P2"])
    speeches = [
        "我愿意和NOVA外出找物资，但还没有谁能保证门外安全。NOVA，你愿意同行吗？其他人也说说对这份名单的顾虑。",
        "我愿意同行，但这并不表示我能担保谁。若有人反对这份名单，请说清楚担忧的是哪一点，我也想平安回来。",
        "P1和NOVA都愿意外出，我暂时没有反对的证据。ECHO，你更担心外出的人选，还是留下的人彼此不信任？",
        "ATLAS，我担心的是我们还不了解彼此。我暂时接受这份名单，但请P1解释为何选NOVA同行。",
        "我听见双方的顾虑了，眼下没有谁能凭一句承诺让我放心。先把选人的理由说清楚，再决定是否接受。",
    ]
    result = []
    for i, pid in enumerate(game.speaking_order):
        observe()
        if pid != "P1":
            agent = agents[pid]
            try:
                agent.prepare(game.view(pid))
            except Captured:
                pass
            context = deepcopy(agent.client.context)
            result.append({"id": pid, "agent": deepcopy(agent), "game": deepcopy(game),
                           "context": context, "context_sha256": digest(context),
                           "protocol": "performance" if "tactical" in context else "policy"})
        game.social(pid, {"card": "HEDGE", "target": "P2" if pid == "P1" else "P1",
                          "reason": "observe", "statement": speeches[i],
                          "rationale": "目前只有公开表态，尚无外出结果，需要听清彼此的理由。", "evidence": []})
    return result


_active = threading.local()
USAGE_KEYS = ("prompt_tokens", "completion_tokens", "total_tokens",
              "prompt_cache_hit_tokens", "prompt_cache_miss_tokens")


@contextmanager
def record_transport():
    """Observe the real ChatClient transport without changing its request body."""
    original = llm.build_opener

    class Response:
        def __init__(self, response, row):
            self.response, self.row = response, row

        def __enter__(self):
            self.response.__enter__()
            return self

        def __exit__(self, *args):
            return self.response.__exit__(*args)

        def read(self, size):
            raw = self.response.read(size)
            try:
                body = json.loads(raw)
                usage = body.get("usage", {})
                self.row["usage"] = {k: usage[k] for k in USAGE_KEYS
                                     if type(usage.get(k)) is int}
                reasoning = usage.get("completion_tokens_details", {}).get("reasoning_tokens")
                if type(reasoning) is int:
                    self.row["usage"]["reasoning_tokens"] = reasoning
                model = body.get("model")
                if isinstance(model, str) and re.fullmatch(r"[\w.\-/]{1,120}", model):
                    self.row["returned_model"] = model
                finish = body["choices"][0].get("finish_reason")
                if finish in {"stop", "length", "tool_calls", "content_filter",
                              "insufficient_system_resource", "aborted"}:
                    self.row["finish_reason"] = finish
                self.row["response_bytes"] = len(raw)
            except (ValueError, TypeError, KeyError, IndexError, AttributeError):
                pass
            return raw

    class Opener:
        def __init__(self, *handlers):
            self.opener = original(*handlers)

        def open(self, request, timeout):
            row = _active.row
            row["request_bytes"] = len(request.data)
            row["request_body_sha256"] = hashlib.sha256(request.data).hexdigest()
            started = time.perf_counter()
            response = self.opener.open(request, timeout=timeout)
            # HTTP headers may precede keep-alive whitespace: this is NOT TTFT.
            row["headers_received_s"] = round(time.perf_counter() - started, 6)
            return Response(response, row)

    with patch.object(llm, "build_opener", Opener):
        yield


class MeasuredClient(llm.ChatClient):
    def __init__(self, settings, expected_context):
        super().__init__(settings)
        self.expected_context = expected_context
        self.attempts = []

    def complete(self, context):
        context_hash = digest(context)
        if not self.attempts and context_hash != self.expected_context:
            raise RuntimeError("Benchmark input changed")
        row = {"attempt": len(self.attempts) + 1, "context_sha256": context_hash}
        self.attempts.append(row)
        _active.row = row
        started = time.perf_counter()
        try:
            result = super().complete(context)
            row["parsed_json_characters"] = len(json.dumps(result, ensure_ascii=False))
            return result
        except llm.LLMError as error:
            row["error"] = str(error)
            raise
        finally:
            row["http_wall_s"] = round(time.perf_counter() - started, 6)
            _active.row = None


def error_fields(error):
    if isinstance(error, llm.LLMError):
        return {"error": str(error), "validation_reason": error.validation_reason}
    # Do not serialize arbitrary exceptions or provider text.
    return {"error": "benchmark_" + type(error).__name__}


def run_job(fixture, settings, batch_start):
    agent, game = deepcopy(fixture["agent"]), deepcopy(fixture["game"])
    client = MeasuredClient(settings, fixture["context_sha256"])
    agent.client = client
    agent.max_retries, agent.retry_delay = settings.max_retries, settings.retry_delay
    started = time.perf_counter()
    row = {"fixture": fixture["id"], "protocol": fixture["protocol"],
           "started_offset_s": round(started - batch_start, 6), "valid": False}

    def on_retry(error, number, delay):
        client.attempts[-1].update(error_fields(error), retry_delay_s=delay)

    try:
        agent.prepare(game.view(agent.id), on_retry=on_retry)
        action = agent.discussion_action()
        game.act(agent.id, action)  # Validate on a private copy, never a live game.
        row["valid"] = True
        row["action"] = action["kind"]
        row["speech_published_by_action"] = "social" in action
        # Only prose that passed the existing public-speech guards is retained.
        social = agent.plan["social"]
        row["social"] = {k: social[k] for k in
                         ("card", "target", "reason", "statement", "rationale", "evidence")}
        row["statement_characters"] = len(social["statement"])
        row["rationale_characters"] = len(social["rationale"])
        terms = r"好人|坏人|阵营|梅林|Merlin|胜率|概率|AI|模型|战术|策略模式|system prompt"
        row["style_review_flags"] = sorted(set(re.findall(
            terms, social["statement"] + social["rationale"], re.IGNORECASE)))
    except Exception as error:
        row.update(error_fields(error))
        if client.attempts:
            client.attempts[-1].update(error_fields(error))
    finished = time.perf_counter()
    row.update(job_wall_s=round(finished - started, 6),
               finished_offset_s=round(finished - batch_start, 6),
               http_attempts=len(client.attempts), retries=max(0, len(client.attempts) - 1),
               attempts=client.attempts)
    return row


def append_json(path, value):
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(value, ensure_ascii=False, allow_nan=False) + "\n")


def run_batch(cases, settings, workers, block, output, *, warmup=False):
    start = time.perf_counter()
    rows = []
    with ThreadPoolExecutor(max_workers=workers) as pool:
        pending = {pool.submit(run_job, case, settings, start): case["id"] for case in cases}
        for future in as_completed(pending):
            row = future.result()
            row.update(workers=workers, block=block, warmup=warmup)
            rows.append(row)
            append_json(output / "requests.jsonl", row)
            print(json.dumps({"event": "job_done", **{k: row[k] for k in
                  ("fixture", "workers", "block", "warmup", "valid", "job_wall_s", "retries")}},
                  ensure_ascii=False), flush=True)
    rows.sort(key=lambda row: [case["id"] for case in cases].index(row["fixture"]))
    batch = {"workers": workers, "block": block, "warmup": warmup,
             "wall_s": round(time.perf_counter() - start, 6),
             "first_ordered_result_s": rows[0]["finished_offset_s"] if rows[0]["valid"] else None,
             "first_valid_completion_s": min((r["finished_offset_s"] for r in rows if r["valid"]), default=None),
             "valid_jobs": sum(r["valid"] for r in rows), "jobs": rows}
    append_json(output / "batches.jsonl", {k: v for k, v in batch.items() if k != "jobs"})
    print(json.dumps({"event": "batch_done", "workers": workers, "block": block,
                      "warmup": warmup, "wall_s": batch["wall_s"], "valid_jobs": batch["valid_jobs"]}), flush=True)
    return batch


def summarize(batches):
    groups = {}
    for workers in sorted({b["workers"] for b in batches if not b["warmup"]}):
        selected = [b for b in batches if b["workers"] == workers and not b["warmup"]]
        rows = [r for b in selected for r in b["jobs"]]
        attempts = [a for r in rows for a in r["attempts"]]
        lengths = [r["statement_characters"] for r in rows if r["valid"]]
        groups[str(workers)] = {
            "batches": len(selected), "jobs": len(rows), "valid_jobs": sum(r["valid"] for r in rows),
            "batch_wall_s": [b["wall_s"] for b in selected],
            "median_batch_wall_s": statistics.median(b["wall_s"] for b in selected),
            "mean_job_wall_s": statistics.mean(r["job_wall_s"] for r in rows),
            "mean_http_wall_s": statistics.mean(a["http_wall_s"] for a in attempts) if attempts else None,
            "first_ordered_result_s": [b["first_ordered_result_s"] for b in selected],
            "http_attempts": len(attempts), "retries": sum(r["retries"] for r in rows),
            "mean_statement_characters": statistics.mean(lengths) if lengths else None,
            "published_speeches": sum(r.get("speech_published_by_action", False) for r in rows),
            "style_flagged_jobs": sum(bool(r.get("style_review_flags")) for r in rows),
            "usage_totals": {k: sum(a.get("usage", {}).get(k, 0) for a in attempts) for k in USAGE_KEYS},
            "usage_responses": sum("usage" in a for a in attempts),
        }
    return groups


def save_summary(output, metadata, batches, status):
    summary = {"metadata": metadata, "status": status, "groups": summarize(batches),
               "total_http_attempts_including_warmup": sum(r["http_attempts"] for b in batches for r in b["jobs"])}
    (output / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--live", action="store_true", help="Make real, billable requests using project configuration")
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--workers", type=int, nargs="+", default=[1, 2, 4])
    parser.add_argument("--skip-warmup", action="store_true")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    if not 1 <= args.repeats <= 10 or not args.workers or any(w not in (1, 2, 4) for w in args.workers):
        parser.error("Use 1–10 repeats and workers from 1, 2, 4")
    if len(set(args.workers)) != len(args.workers):
        parser.error("Workers must be distinct")
    settings = llm.Settings.load()
    cases = fixtures()
    client = llm.ChatClient(settings)
    metadata = {
        "started_at_utc": datetime.now(timezone.utc).isoformat(),
        "settings": {k: getattr(settings, k) for k in ("base_url", "model", "timeout", "max_tokens",
                     "token_field", "json_mode", "thinking", "max_retries", "retry_delay")},
        "workers": args.workers, "repeats": args.repeats, "warmup": not args.skip_warmup,
        "scope": "identical recorded scripted-game contexts; not live interdependent gameplay",
        "timing": "non-streaming full response; header time is not first-token time",
        "fixtures": [{"id": c["id"], "protocol": c["protocol"], "context_sha256": c["context_sha256"],
                      "context_characters": len(json.dumps(c["context"], ensure_ascii=False)),
                      "visible_events": len(c["context"]["game"]["recent_events"]),
                      "system_characters": len(client._system_prompts["tactical" in c["context"]]),
                      "system_sha256": digest(client._system_prompts["tactical" in c["context"]])} for c in cases],
    }
    if not args.live:
        print(json.dumps({"dry_run": True, "planned_base_calls": 4 * (args.repeats * len(args.workers)
                          + int(not args.skip_warmup)), **metadata}, ensure_ascii=False, indent=2))
        return
    if not settings.ready:
        parser.error("Project API configuration is missing")
    output = args.output or ROOT / "experiments" / "llm-concurrency" / datetime.now().strftime("%Y%m%d-%H%M%S")
    output.mkdir(parents=True, exist_ok=False)
    (output / "metadata.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"event": "start", "output": str(output.resolve()), "metadata": metadata}, ensure_ascii=False), flush=True)
    batches = []
    with record_transport():
        if not args.skip_warmup:
            batches.append(run_batch(cases, settings, max(args.workers), 0, output, warmup=True))
            save_summary(output, metadata, batches, "running")
            if not batches[-1]["valid_jobs"]:
                save_summary(output, metadata, batches, "stopped_all_warmup_jobs_failed")
                raise SystemExit("All warmup jobs failed; stopped before more billable requests")
        for block in range(args.repeats):
            # Rotate to balance provider drift and cache/order effects across modes.
            offset = block % len(args.workers)
            order = args.workers[offset:] + args.workers[:offset]
            for workers in order:
                batches.append(run_batch(cases, settings, workers, block + 1, output))
                save_summary(output, metadata, batches, "running")
    summary = save_summary(output, metadata, batches, "complete")
    print(json.dumps({"event": "complete", "output": str(output.resolve()), "groups": summary["groups"]}, ensure_ascii=False), flush=True)


if __name__ == "__main__":
    main()
